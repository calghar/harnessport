import { describe, it, expect } from "vitest";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import * as fs from "node:fs";
import * as os from "node:os";
import { claudeConverter } from "../src/converters/claude.js";
import { opencodeConverter } from "../src/converters/opencode.js";
import { cursorConverter } from "../src/converters/cursor.js";
import { copilotConverter } from "../src/converters/copilot.js";
import { codexConverter } from "../src/converters/codex.js";
import type { Capability, Converter } from "../src/converters/types.js";
import { syncReadme } from "../src/matrix.js";
import type { Feature, FidelityItem, HarnessConfig } from "../src/schema.js";

const HERE = path.dirname(fileURLToPath(import.meta.url));

// Mirrors features/capability-declaration.feature and features/conversion-reporting.feature,
// generated by openspec-bdd from openspec/changes/capability-matrix/specs/.

const CONVERTERS: Record<string, Converter> = {
  claude: claudeConverter,
  opencode: opencodeConverter,
  cursor: cursorConverter,
  copilot: copilotConverter,
  codex: codexConverter,
};

const FEATURES: Feature[] = [
  "rule", "agent", "skill", "command",
  "mcp", "permission", "hook", "formatter",
];

const CAPABILITIES: Capability[] = ["full", "user-level", "none"];

function tmpDir(): string {
  return fs.mkdtempSync(path.join(os.tmpdir(), "harnessport-cap-"));
}

/** A config holding one of every feature, so every converter has something to report on. */
function everyFeature(): HarnessConfig {
  return {
    rules: [{ content: "Be careful.", source: "rules.md" }],
    agents: [{ name: "reviewer", body: "Review it.", description: "Reviews code" }],
    skills: [{ name: "testing", body: "Test it." }],
    commands: [{ name: "ship", body: "Ship it." }],
    mcpServers: [{ name: "fs", type: "stdio", command: "npx", args: ["mcp-fs"] }],
    permissions: [{ tool: "bash", pattern: "npm run:*", action: "allow" }],
    hooks: [{ event: "PreToolUse", matcher: "Bash", command: "./guard.sh" }],
    formatters: [{ glob: "*.py", command: "ruff format" }],
    items: [],
  };
}

/** Export to a real directory — dry runs never execute the serialization path. */
function exportEveryFeature(converter: Converter): FidelityItem[] {
  return converter.export(tmpDir(), everyFeature(), {}).items;
}

function itemsOfKind(items: FidelityItem[], kind: Feature): FidelityItem[] {
  return items.filter((i) => i.kind === kind);
}

describe("Requirement: A declaration disagreeing with export behaviour fails the build", () => {
  it("every converter declares each feature and agrees with its own export", () => {
    for (const [name, converter] of Object.entries(CONVERTERS)) {
      const items = exportEveryFeature(converter);
      for (const feature of FEATURES) {
        expect(CAPABILITIES, `${name}/${feature}`).toContain(converter.capabilities[feature]);
        const written = itemsOfKind(items, feature).some((i) => i.status === "exact" || i.status === "lossy");
        expect(written, `${name}/${feature}`).toBe(converter.capabilities[feature] === "full");
      }
    }
  });
});

describe("Requirement: The README matrix is generated and drift fails the check", () => {
  const README = path.resolve(HERE, "..", "README.md");

  it("A matching README passes the check", () => {
    expect(syncReadme(README, { check: true }).drifted).toBe(false);
  });

  it("An edited README fails the check", () => {
    const dir = tmpDir();
    const copy = path.join(dir, "README.md");
    fs.writeFileSync(
      copy,
      fs.readFileSync(README, "utf-8").replace("| Cursor ", "| Kursor "),
    );
    const outcome = syncReadme(copy, { check: true });
    expect(outcome.drifted).toBe(true);
    expect(outcome.message).toContain("npm run docs:matrix");
  });

});

describe("Requirement: A guardrail a target cannot write or enforce is blocked", () => {
  const exportHook = (event: string) =>
    opencodeConverter.export(
      tmpDir(),
      { ...everyFeature(), hooks: [{ event, matcher: "Bash", command: "./h.sh" }] },
      {},
    ).items;
  const exitCode = (items: FidelityItem[]) => (items.some((i) => i.status === "blocked") ? 2 : 0);

  it("A claude PreToolUse hook exported to opencode is blocked", () => {
    const items = exportHook("PreToolUse");
    const [item] = itemsOfKind(items, "hook");
    expect(item.name).toBe("PreToolUse");
    expect(item.status).toBe("blocked");
    expect(item.reason).toContain("tool.execute.before");
    expect(exitCode(items)).toBe(2);
  });

  it("A claude PostToolUse hook exported to opencode is dropped", () => {
    const items = exportHook("PostToolUse");
    const [item] = itemsOfKind(items, "hook");
    expect(item.name).toBe("PostToolUse");
    expect(item.status).toBe("dropped");
    expect(exitCode(items)).toBe(0);
  });
});

describe("Requirement: Cursor converts hooks through its wrapper", () => {
  it("declares hook as full", () => {
    expect(cursorConverter.capabilities.hook).toBe("full");
  });
});
