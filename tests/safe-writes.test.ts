import { describe, it, expect } from "vitest";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import * as fs from "node:fs";
import * as os from "node:os";
import { spawnSync } from "node:child_process";
import { claudeConverter } from "../src/converters/claude.js";
import { opencodeConverter } from "../src/converters/opencode.js";
import type { HarnessConfig } from "../src/schema.js";

const HERE = path.dirname(fileURLToPath(import.meta.url));

// Mirrors features/safe-writes.feature, features/output-naming.feature, and the
// conversion-reporting delta, generated by openspec-bdd from
// openspec/changes/safe-writes/specs/.

const FIXTURES = path.resolve(HERE, "fixtures");
const SAMPLE = path.join(FIXTURES, "sample-project");
const CLI = path.resolve(HERE, "..", "dist", "index.js");
const _hasBuild = fs.existsSync(CLI);

function tmpDir(): string {
  return fs.mkdtempSync(path.join(os.tmpdir(), "harnessport-sw-"));
}

function _run(args: string[]) {
  return spawnSync("node", [CLI, ...args], { encoding: "utf-8" });
}

function emptyConfig(over: Partial<HarnessConfig> = {}): HarnessConfig {
  return {
    rules: [], agents: [], skills: [], commands: [],
    mcpServers: [], permissions: [], hooks: [], formatters: [], items: [],
    ...over,
  } as HarnessConfig;
}

describe("Requirement: An existing file is never silently overwritten", () => {
  it("A differing file is left untouched", () => {
    const dir = tmpDir();
    const target = path.join(dir, "AGENTS.md");
    fs.writeFileSync(target, "# Hand written\n\nDo not clobber me.\n");
    const original = fs.readFileSync(target, "utf-8");

    const config = claudeConverter.import(SAMPLE);
    const result = opencodeConverter.export(dir, config, {});

    expect(fs.readFileSync(target, "utf-8")).toBe(original);
    expect(
      result.items.some((i) => i.status === "blocked" && i.name.includes("AGENTS.md")),
    ).toBe(true);
  });

});

describe("Requirement: Forcing an overwrite preserves the original", () => {
  it("Force writes the new content and keeps a backup", () => {
    const dir = tmpDir();
    const target = path.join(dir, "AGENTS.md");
    const original = "# Hand written\n\nKeep me in a bak.\n";
    fs.writeFileSync(target, original);

    const config = claudeConverter.import(SAMPLE);
    opencodeConverter.export(dir, config, { force: true });

    expect(fs.readFileSync(`${target}.bak`, "utf-8")).toBe(original);
    expect(fs.readFileSync(target, "utf-8")).not.toBe(original);
  });

});

describe("Requirement: A dry run writes nothing", () => {
  it("Dry run leaves a conflicting file untouched and still reports it", () => {
    const dir = tmpDir();
    const target = path.join(dir, "AGENTS.md");
    const original = "# untouched\n";
    fs.writeFileSync(target, original);

    const config = claudeConverter.import(SAMPLE);
    const result = opencodeConverter.export(dir, config, { dryRun: true });

    expect(fs.readFileSync(target, "utf-8")).toBe(original);
    expect(
      result.items.some((i) => i.status === "blocked" && i.name.includes("AGENTS.md")),
    ).toBe(true);
  });

});

describe("Requirement: Two inputs never collapse onto one output file", () => {
  it("Skills differing only by case each get a file", () => {
    const dir = tmpDir();
    const config = emptyConfig({
      skills: [
        { name: "Testing", body: "upper body" },
        { name: "testing", body: "lower body" },
      ],
    });
    opencodeConverter.export(dir, config, {});

    const skillFiles: string[] = [];
    const walk = (d: string) => {
      for (const e of fs.readdirSync(d, { withFileTypes: true })) {
        const p = path.join(d, e.name);
        if (e.isDirectory()) walk(p);
        else if (e.name === "SKILL.md") skillFiles.push(fs.readFileSync(p, "utf-8"));
      }
    };
    walk(dir);

    expect(skillFiles).toHaveLength(2);
    expect(skillFiles.join("\n")).toContain("upper body");
    expect(skillFiles.join("\n")).toContain("lower body");
  });

});

describe("Requirement: Malformed input is distinguishable from absent input", () => {
  it("A malformed JSON config is reported, not silently empty", () => {
    const dir = tmpDir();
    fs.mkdirSync(path.join(dir, ".claude"), { recursive: true });
    fs.writeFileSync(path.join(dir, ".claude", "CLAUDE.md"), "# rules\n");
    fs.writeFileSync(path.join(dir, ".mcp.json"), '{ "mcpServers": { broken ]');

    const config = claudeConverter.import(dir);
    expect(
      config.items.some(
        (i) => i.phase === "import" && i.status === "blocked" && i.name.includes(".mcp.json"),
      ),
    ).toBe(true);
  });

});
